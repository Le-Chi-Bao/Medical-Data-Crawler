"""Offline Vietnamese synthetic demo. Never counted as acquired medical documents."""

import hashlib
import json
from datetime import UTC, datetime, timedelta
from pathlib import Path
from uuid import uuid4

from medical_data_crawler.curated import CuratedPublicDocumentImporter, verify_report
from medical_data_crawler.curated_manifest import digest


def main():
    root = Path("data/curated-synthetic-demo") / uuid4().hex
    intake = root / "intake"
    intake.mkdir(parents=True)
    path = intake / "synthetic.html"
    data = (
        '<!doctype html><html lang="vi"><meta charset="utf-8"><body><article>'
        "<h1>Mẫu tổng hợp</h1><p>Đây là dữ liệu kiểm thử tiếng Việt, "
        "không phải tài liệu y khoa thật.</p></article></body></html>"
    ).encode()
    path.write_bytes(data)
    now = datetime.now(UTC)
    doc = dict(
        document_id="synthetic-vietnamese-demo",
        title="Mẫu tổng hợp",
        publisher="Synthetic demo",
        original_publisher="Synthetic demo",
        source_url="https://example.org/synthetic-demo",
        download_url=None,
        language="vi",
        published_on=None,
        format="html",
        category="unknown",
        scope=[],
        scope_evidence=None,
        local_path=str(path.absolute()),
        expected_sha256=hashlib.sha256(data).hexdigest(),
        submitted_at=now.isoformat(),
        data_origin="synthetic",
        source_status="verified",
        verified_at=now.isoformat(),
        access_status="unverified",
        review_notes="Generated locally; no medical claims.",
        rights=dict(
            status="reviewed",
            license_uri=None,
            evidence_url=None,
            evidence_note="Synthetic bytes generated by this demo for testing.",
            allowed_operations=["read", "store", "extract"],
        ),
    )
    grant = dict(
        document_id=doc["document_id"],
        manifest_entry_sha256=digest(doc),
        expected_sha256=doc["expected_sha256"],
        allowed_operations=["read", "store", "extract"],
        reviewer="synthetic-demo",
        evidence="Demo owns synthetic bytes it generated.",
        expires_at=(now + timedelta(hours=1)).isoformat(),
        active=True,
    )
    manifest = dict(curated_manifest_version="0.1", documents=[doc])
    runner = CuratedPublicDocumentImporter(
        intake_root=intake,
        state_root=root,
        approvals=dict(curated_approval_version="0.1", approvals=[grant]),
    )
    first = runner.run(manifest)
    second = runner.run(manifest)
    report = root / "reports" / second["run_id"] / "report.json"
    verification = verify_report(report, root)
    print(
        json.dumps(
            dict(
                first=first["summary"],
                second=second["summary"],
                duplicate=second["items"][0]["duplicate"],
                verification=verification,
                report=str(report),
            ),
            ensure_ascii=False,
            indent=2,
        )
    )
    return 0 if verification["integrity"] == "verified" and not second["batch_error"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
